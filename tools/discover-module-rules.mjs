/**
 * Find the rules Ansible modules check in code rather than in their
 * documentation — "one of the following is required", "state is present but
 * any of the following are missing", "parameters are required together" — by
 * checking every per-module blueprint with ansible-lint's argument rule, with
 * nothing filled in, and reading the errors.
 *
 * The Ansible counterpart of tools/discover-resource-rules.mjs. Each rule
 * found goes into src/ansible/module-rules-data.ts, which the blueprints use:
 * a stand-in variable when none of a "one of" group is set, the rest of a
 * "together" group once one is, and "set this or that" beside each member.
 *
 *   npm run ansible:rules                    # every per-module blueprint
 *   npm run ansible:rules -- mod_cisco_      # ids containing this
 *
 * Runs in rounds until one finds nothing new. Needs the Ansible in
 * ~/archtoolkit-ansible; see tools/validate-ansible-blueprints.mjs.
 */

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'src', 'ansible', 'module-rules-data.ts');
const VALIDATE = join(HERE, 'validate-ansible-blueprints.mjs');
const prefixes = process.argv.slice(2).filter((a) => !a.startsWith('-'));

function readRules() {
  try {
    const m = /DISCOVERED_MODULE_RULES: any = (\{[\s\S]*\});\s*$/.exec(readFileSync(OUT, 'utf8'));
    return m ? JSON.parse(m[1]) : {};
  } catch {
    return {};
  }
}

function writeRules(rules) {
  const sorted = Object.fromEntries(Object.keys(rules).sort().map((k) => [k, rules[k]]));
  writeFileSync(
    OUT,
    `/**
 * Module rules found by running ansible-lint — GENERATED by
 * tools/discover-module-rules.mjs, do not edit by hand.
 *
 * Per module (FQCN):
 *   oneOf  groups of options of which one has to be set; the first stands in
 *   allOf  groups set together: once one is, the rest are needed too
 * Paths are dotted through suboptions.
 */

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export const DISCOVERED_MODULE_RULES: any = ${JSON.stringify(sorted, null, 1)};
`,
  );
}

/** `a, b, c` → [a, b, c], under the suboption path `found in x -> y` names, if any. */
function names(list, where) {
  const prefix = where ? `${where.split(/\s*->\s*/).join('.')}.` : '';
  return list
    .split(',')
    .map((s) => s.trim().replace(/^['"]|['"]$/g, ''))
    .filter(Boolean)
    .map((n) => prefix + n);
}

function rulesFrom(problems) {
  const oneOf = [];
  const allOf = [];
  for (const line of problems) {
    const text = line.replace(/^args\[module\]:\s*/, '');
    const where = / found in (.+?)\.?$/.exec(text)?.[1];
    const body = text.replace(/ found in .+$/, '');
    let m;
    if ((m = /one of the following is required: (.+)$/.exec(body))) oneOf.push(names(m[1], where));
    else if ((m = /but any of the following are missing: (.+)$/.exec(body))) oneOf.push(names(m[1], where));
    else if ((m = /but all of the following are missing: (.+)$/.exec(body))) for (const n of names(m[1], where)) oneOf.push([n]);
    else if ((m = /missing required arguments: (.+)$/.exec(body))) for (const n of names(m[1], where)) oneOf.push([n]);
    else if ((m = /parameters are required together: (.+)$/.exec(body))) allOf.push(names(m[1], where));
    else if ((m = /missing parameter\(s\) required by '([^']+)': (.+)$/.exec(body))) allOf.push([...names(m[1], where), ...names(m[2], where)]);
    else if ((m = /At least one of `([^`]+)` or `([^`]+)`/.exec(body))) oneOf.push(names(`${m[1]}, ${m[2]}`, where));
  }
  return { oneOf, allOf };
}

function merge(into, found) {
  const rule = { ...(into ?? {}) };
  let added = 0;
  for (const kind of ['oneOf', 'allOf']) {
    for (const group of found[kind]) {
      const key = [...group].sort().join(',');
      if (group.length > 0 && !(rule[kind] ?? []).some((g) => [...g].sort().join(',') === key)) {
        rule[kind] = [...(rule[kind] ?? []), group];
        added++;
      }
    }
  }
  return { rule, added };
}

/** The module a blueprint id is for: `mod_cisco_ios_ios_vlans` → `cisco.ios.ios_vlans`. */
function fqcnOf(id, known) {
  return known.get(id);
}

const work = mkdtempSync(join(tmpdir(), 'archtoolkit-module-rules-'));
try {
  // Blueprint id → FQCN, from the index (ids flatten the dots).
  const indexText = readFileSync(join(HERE, '..', 'src', 'ansible', 'module-schema-index.ts'), 'utf8');
  const index = JSON.parse(JSON.parse(/JSON\.parse\((".*")\);/s.exec(indexText)[1]));
  const known = new Map(Object.keys(index.modules).map((fqcn) => [`mod_${fqcn.replace(/\./g, '_')}`, fqcn]));

  let ids = null;
  for (let round = 1; round <= 5; round++) {
    const report = join(work, `round${round}.json`);
    const args = [...process.execArgv, VALIDATE, '--modules', '--report', report];
    if (ids) {
      const list = join(work, `ids${round}.txt`);
      writeFileSync(list, ids.join('\n'));
      args.push('--ids', list);
    } else {
      for (const p of prefixes) args.push('--only', p);
    }
    console.log(`Round ${round}: checking ${ids ? ids.length : 'every'} per-module blueprint${ids?.length === 1 ? '' : 's'}…`);
    const run = spawnSync(process.execPath, args, { stdio: ['ignore', 'pipe', 'inherit'], maxBuffer: 512 * 1024 * 1024 });
    console.log(`  ${run.stdout.toString().trim().split('\n').pop()}`);
    let failures;
    try {
      failures = JSON.parse(readFileSync(report, 'utf8'));
    } catch {
      console.log('  No report was written; stopping.');
      break;
    }
    const rules = readRules();
    let added = 0;
    const retry = [];
    const unexplained = [];
    for (const [id, problems] of Object.entries(failures)) {
      const fqcn = fqcnOf(id, known);
      if (!fqcn) continue;
      const merged = merge(rules[fqcn], rulesFrom(problems));
      if (merged.added > 0) {
        rules[fqcn] = merged.rule;
        added += merged.added;
        retry.push(id);
      } else {
        unexplained.push(`${id}: ${problems[0]}`);
      }
    }
    writeRules(rules);
    console.log(`  ${added} new rule${added === 1 ? '' : 's'} across ${retry.length} module${retry.length === 1 ? '' : 's'}.`);
    if (unexplained.length > 0) {
      console.log(`  ${unexplained.length} failure${unexplained.length === 1 ? '' : 's'} no rule explains:`);
      for (const line of unexplained.slice(0, 60)) console.log(`    ${line.slice(0, 240)}`);
    }
    if (retry.length === 0) break;
    ids = retry;
  }
} finally {
  rmSync(work, { recursive: true, force: true, maxRetries: 5, retryDelay: 500 });
}
