/**
 * Find the rules the providers check in code rather than in their schemas —
 * "exactly one of `a`, `b` must be specified", "at least 2 `host` blocks" —
 * by running `terraform validate` over every per-resource blueprint with
 * nothing filled in, and reading the errors.
 *
 * `terraform providers schema -json` cannot say these: they are validators in
 * the provider's Go code. A per-resource blueprint that ignored them would
 * write a file that fails `terraform validate` as downloaded. So each one found
 * is recorded in src/terraform/resource-rules-data.ts, and the blueprint uses
 * it: the first of a "one of" group becomes a variable (or its block is
 * included) when none is set, a minimum block count is honoured, and the form
 * says "set this or that" beside each member.
 *
 *   npm run rules:discover                    # every per-resource blueprint
 *   npm run rules:discover -- res_aws_        # ids starting with this
 *
 * Runs in rounds — a rule found can uncover the next error in the same
 * resource — until a round finds nothing new. Needs the terraform CLI; see
 * tools/validate-terraform-blueprints.mjs, which it drives.
 */

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'src', 'terraform', 'resource-rules-data.ts');
const VALIDATE = join(HERE, 'validate-terraform-blueprints.mjs');
const PER_RESOURCE = /^(vmw|lnx|win|res)_/;

const prefixes = process.argv.slice(2).filter((a) => !a.startsWith('-'));

function readRules() {
  try {
    const text = readFileSync(OUT, 'utf8');
    const m = /DISCOVERED_RULES: any = (\{[\s\S]*\});\s*$/.exec(text);
    return m ? JSON.parse(m[1]) : {};
  } catch {
    return {};
  }
}

function writeRules(rules) {
  const sorted = Object.fromEntries(Object.keys(rules).sort().map((k) => [k, rules[k]]));
  writeFileSync(
    OUT,
    `/**
 * Provider rules found by running \`terraform validate\` — GENERATED by
 * tools/discover-resource-rules.mjs, do not edit by hand.
 *
 * Per resource type:
 *   oneOf      groups of arguments of which one has to be set; the first
 *              stands in (as a variable, or its block included) when none is
 *   allOf      groups that are set together: once one is, the rest become
 *              variables too
 *   minBlocks  nested blocks, by path, that need more copies than the schema says
 */

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export const DISCOVERED_RULES: any = ${JSON.stringify(sorted, null, 1)};
`,
  );
}

/**
 * A provider's path, as the blueprints name it: `credential.0.saml_login`,
 * `rule[0].action` and `policy_detail[Value({…})].action` lose their indexes,
 * and `name_pattern.<.name_prefix` (a sibling of name_pattern) resolves to
 * `name_prefix`.
 */
function normalise(path) {
  // Index brackets can hold brackets of their own ([Value({"a":[{…}]})]).
  let flat = '';
  let depth = 0;
  for (const c of path.trim().replace(/["\s]/g, '')) {
    if (c === '[') depth++;
    else if (c === ']') depth--;
    else if (depth === 0) flat += c;
  }
  const parts = flat
    .split('.')
    .filter((p) => p !== '' && !/^\d+$/.test(p));
  const out = [];
  for (const part of parts) {
    if (part === '<') out.pop();
    else out.push(part);
  }
  return out.join('.');
}

/**
 * The comma-separated list in `[...]` starting at `from`, which may itself hold
 * brackets: `[resource_data[0].catalog,resource_data[0].data_location]`.
 */
function bracketList(text, from) {
  const open = text.indexOf('[', from);
  if (open === -1) return [];
  let depth = 0;
  let item = '';
  const items = [];
  for (let i = open; i < text.length; i++) {
    const c = text[i];
    if (c === '[') {
      depth++;
      if (depth === 1) continue;
    }
    if (c === ']') {
      depth--;
      if (depth === 0) {
        items.push(item);
        return items;
      }
    }
    if (c === ',' && depth === 1) {
      items.push(item);
      item = '';
      continue;
    }
    item += c;
  }
  return items;
}

/**
 * The member to stand in goes first: a top-level argument before a nested one
 * (whose block may not be there), and a plain one before its write-only
 * (`_wo`) twin.
 */
function order(group) {
  const rank = (p) => (p.includes('.') ? 2 : 0) + (/_wo(_|$)/.test(p) ? 1 : 0);
  return [...new Set(group.map(normalise))].sort((a, b) => rank(a) - rank(b));
}

function rulesFrom(diagnostics) {
  const oneOf = [];
  const allOf = [];
  const minBlocks = {};
  for (const { summary, detail } of diagnostics) {
    const text = `${summary} — ${detail}`;
    let m;
    if ((m = /one of `([^`]+)` must be specified/.exec(text))) oneOf.push(order(m[1].split(',')));
    else if ((m = /all of `([^`]+)` must be specified/.exec(text))) allOf.push(order(m[1].split(',')));
    else if ((m = /At least one of `([^`]+)` or `([^`]+)` must be set/.exec(text))) oneOf.push(order([m[1], m[2]]));
    else if ((m = /either (\w+) or (\w+) must be present/.exec(text))) oneOf.push(order([m[1], m[2]]));
    else if ((m = /(?:Exactly one of these attributes must be configured|At least one of these attributes must be configured|one \(and only one\) of|At least one attribute out of|at least one of)\s*:?\s*(?=\[)/i.exec(text))) {
      // `a.<.b` means "b, a sibling of a": both are in the group.
      const group = bracketList(text, m.index + m[0].length).flatMap((item) =>
        item.includes('.<.') ? [item.slice(0, item.indexOf('.<.')), item] : [item],
      );
      if (group.length > 0) oneOf.push(order(group));
    } else if ((m = /At least (\d+) "([^"]+)" blocks? (?:is|are) required/.exec(text))) minBlocks[m[2]] = Number(m[1]);
    else if ((m = /Block (\S+) must have a configuration value/.exec(text))) minBlocks[normalise(m[1])] = 1;
  }
  return { oneOf, allOf, minBlocks };
}

function merge(into, found) {
  let added = 0;
  const rule = { ...(into ?? {}) };
  for (const group of found.oneOf) {
    const key = [...group].sort().join(',');
    const have = (rule.oneOf ?? []).map((g) => [...g].sort().join(','));
    if (group.length > 0 && !have.includes(key)) {
      rule.oneOf = [...(rule.oneOf ?? []), group];
      added++;
    }
  }
  for (const group of found.allOf) {
    const key = [...group].sort().join(',');
    const have = (rule.allOf ?? []).map((g) => [...g].sort().join(','));
    if (group.length > 1 && !have.includes(key)) {
      rule.allOf = [...(rule.allOf ?? []), group];
      added++;
    }
  }
  // A group seen before whose first member was nested: put a top-level one first.
  if (rule.oneOf) rule.oneOf = rule.oneOf.map(order);
  for (const [path, count] of Object.entries(found.minBlocks)) {
    if ((rule.minBlocks?.[path] ?? 0) < count) {
      rule.minBlocks = { ...(rule.minBlocks ?? {}), [path]: count };
      added++;
    }
  }
  return { rule, added };
}

const work = mkdtempSync(join(tmpdir(), 'archtoolkit-rules-'));
try {
  let ids = null;
  for (let round = 1; round <= 6; round++) {
    const report = join(work, `round${round}.json`);
    // The same Node flags as this run (type stripping on older Node 22s).
    const args = [...process.execArgv, VALIDATE, '--report', report];
    if (ids) {
      const list = join(work, `ids${round}.txt`);
      writeFileSync(list, ids.join('\n'));
      args.push('--ids', list);
    } else {
      args.push('--per-resource');
      for (const p of prefixes) args.push('--only', p);
    }
    console.log(`Round ${round}: validating ${ids ? ids.length : 'every'} per-resource blueprint${ids?.length === 1 ? '' : 's'}…`);
    const run = spawnSync(process.execPath, args, { stdio: ['ignore', 'pipe', 'inherit'], maxBuffer: 256 * 1024 * 1024 });
    const tail = run.stdout.toString().trim().split('\n').pop();
    console.log(`  ${tail}`);
    let failures = {};
    try {
      failures = JSON.parse(readFileSync(report, 'utf8'));
    } catch {
      console.error('  No report was written; stopping.');
      break;
    }
    const rules = readRules();
    let added = 0;
    const retry = [];
    const unexplained = [];
    for (const [id, diagnostics] of Object.entries(failures)) {
      const bare = id.replace(/ \[.*$/, '');
      if (!PER_RESOURCE.test(bare)) continue;
      const type = bare.replace(PER_RESOURCE, '');
      const found = rulesFrom(diagnostics);
      const merged = merge(rules[type], found);
      if (merged.added > 0) {
        rules[type] = merged.rule;
        added += merged.added;
        retry.push(bare);
      } else {
        unexplained.push(`${bare}: ${diagnostics[0]?.summary} — ${(diagnostics[0]?.detail ?? '').split('\n')[0]}`);
      }
    }
    writeRules(rules);
    console.log(`  ${added} new rule${added === 1 ? '' : 's'} across ${retry.length} resource${retry.length === 1 ? '' : 's'}.`);
    if (unexplained.length > 0) {
      console.log(`  ${unexplained.length} failure${unexplained.length === 1 ? '' : 's'} no rule explains:`);
      for (const line of unexplained.slice(0, 40)) console.log(`    ${line}`);
    }
    if (retry.length === 0) break;
    ids = retry;
  }
} finally {
  rmSync(work, { recursive: true, force: true, maxRetries: 5, retryDelay: 500 });
}
