#!/usr/bin/env node
/**
 * Refresh the Azure Resource Manager schema data the data editor checks ARM
 * templates against, from Microsoft's published ARM schemas
 * (github.com/Azure/azure-resource-manager-schemas, `schemas/<apiVersion>/<file>.json`).
 *
 *   npm run editor:arm
 *
 * Two outputs, both committed so the toolkit works air-gapped:
 *
 *  - src/editor/arm-schema-index.ts — every resource type Microsoft publishes a
 *    schema for, with every apiVersion that exists for it (newest first) and
 *    the chunk its property schema is in; plus the fetch date and the commit.
 *  - web/data/editor/arm/<Namespace>.json — per namespace, for each type, the
 *    body of its preferred apiVersion (the newest stable one, or the newest
 *    preview when there is no stable one): fields, types, required fields and
 *    enums, with local `#/definitions` refs and common/definitions.json refs
 *    resolved into a shared, numbered definition table.
 *
 * Where the data comes from:
 *
 *  1. One GitHub API call: the git tree of `main`, recursively, which lists
 *     every schema file, and pins the commit everything else is read from.
 *  2. Which resource types each (apiVersion, file) holds comes from the
 *     repository's own aggregate lists — schemas/common/autogeneratedResources.json
 *     and the subscription, management-group and tenant deployment templates —
 *     whose `$ref`s name every resource definition of every version, so no
 *     old schema file needs downloading to build the index.
 *  3. The preferred-version schema file of each resource definition is then
 *     downloaded from raw.githubusercontent.com (a few hundred files) to get
 *     the type's real name and its properties. Only those, not all ~3,000
 *     files (~275 MB).
 *
 * Unauthenticated, GitHub allows 60 API calls an hour; this makes one, and the
 * raw downloads are not counted against it. If you are rate limited anyway
 * (403/429), set GITHUB_TOKEN in the environment (any token; no scopes needed)
 * and it is sent with every request. Downloads are cached per commit in the OS
 * temp directory, so a rerun against the same commit fetches nothing again.
 *
 * Options: --dry (list what would be downloaded, write nothing).
 */

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const INDEX_OUT = join(ROOT, 'src', 'editor', 'arm-schema-index.ts');
const DATA_OUT = join(ROOT, 'web', 'data', 'editor', 'arm');
const REPO = 'Azure/azure-resource-manager-schemas';
const BRANCH = 'main';
const DRY = process.argv.includes('--dry');
const CONCURRENCY = 6;
/** A namespace chunk past this many bytes is split, a group of top-level types to a file. */
const CHUNK_LIMIT = 900_000;

const TOKEN = process.env.GITHUB_TOKEN || process.env.GH_TOKEN || '';
const HEADERS = { 'User-Agent': 'archtoolkit-fetch-editor-arm', ...(TOKEN ? { Authorization: `Bearer ${TOKEN}` } : {}) };

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function get(url, { json = true } = {}) {
  for (let attempt = 0; ; attempt += 1) {
    let res;
    try {
      res = await fetch(url, { headers: HEADERS });
    } catch (err) {
      if (attempt >= 5) throw err;
      await sleep(1000 * 2 ** attempt);
      continue;
    }
    if (res.ok) return json ? res.json() : res.text();
    if ((res.status === 429 || res.status === 403 || res.status >= 500) && attempt < 6) {
      const retryAfter = Number(res.headers.get('retry-after'));
      const reset = Number(res.headers.get('x-ratelimit-reset'));
      let wait = Number.isFinite(retryAfter) && retryAfter > 0 ? retryAfter * 1000 : 2000 * 2 ** attempt;
      if (res.headers.get('x-ratelimit-remaining') === '0' && reset) wait = Math.max(wait, reset * 1000 - Date.now() + 1000);
      if (wait > 15 * 60_000) throw new Error(`${url}: rate limited until ${new Date(reset * 1000).toISOString()}; set GITHUB_TOKEN and retry.`);
      console.warn(`  ${res.status} on ${url.replace(/^.*\/schemas\//, '')}; waiting ${Math.round(wait / 1000)}s`);
      await sleep(wait);
      continue;
    }
    throw new Error(`${url}: HTTP ${res.status}${res.status === 403 || res.status === 429 ? ' (rate limited? set GITHUB_TOKEN)' : ''}`);
  }
}

async function pool(items, n, fn) {
  let next = 0;
  let done = 0;
  const workers = Array.from({ length: n }, async () => {
    while (next < items.length) {
      const item = items[next++];
      await fn(item);
      done += 1;
      if (done % 25 === 0 || done === items.length) console.log(`  ${done}/${items.length}`);
    }
  });
  await Promise.all(workers);
}

// ------------------------------------------------------------ versions ---

const isStable = (v) => /^\d{4}-\d{2}-\d{2}$/.test(v);
/** Newest first; on the same date, the stable version before its previews. */
function compareVersions(a, b) {
  const da = a.slice(0, 10);
  const db = b.slice(0, 10);
  if (da !== db) return da < db ? 1 : -1;
  if (isStable(a) !== isStable(b)) return isStable(a) ? -1 : 1;
  return a < b ? -1 : a > b ? 1 : 0;
}
const preferred = (versions) => [...versions].sort(compareVersions).find(isStable) ?? [...versions].sort(compareVersions)[0];

// ---------------------------------------------------------- compaction ---

const EXPRESSION_REF = /common\/definitions\.json#\/definitions\/expression$/;
const COMMON_FILE = 'common/definitions';

/**
 * Compact form of a JSON schema node, as src/editor/arm-schema.ts reads it:
 *   t: 's' string | 'i' integer | 'n' number | 'b' boolean | 'o' object | 'a' array
 *   e: string enum
 *   p: properties, r: required, i: items, m: additionalProperties' schema (a map)
 *   d: index of a shared definition in the chunk's `d` table
 *   o: 1 when the object is open (takes fields not listed)
 * An empty object means "anything"; nothing is checked below it.
 */
class Compactor {
  constructor(files) {
    this.files = files; // key "version/file" or COMMON_FILE → parsed schema
    this.defs = [];
    this.ids = new Map();
  }

  /** The definition table index of `#/definitions/<name>` in file `key`, compacting it on first use. */
  def(key, name) {
    const id = `${key}#${name}`;
    if (this.ids.has(id)) return this.ids.get(id);
    const node = this.files.get(key)?.definitions?.[name];
    if (!node) return undefined;
    const index = this.defs.length;
    this.ids.set(id, index);
    this.defs.push({});
    this.defs[index] = this.node(key, node, 0);
    return index;
  }

  ref(key, ref) {
    if (EXPRESSION_REF.test(ref)) return null; // an ARM expression: the alternative every field has
    const local = /^#\/definitions\/(.+)$/.exec(ref);
    if (local) {
      const d = this.def(key, decodeURIComponent(local[1]));
      return d === undefined ? {} : { d };
    }
    const common = /common\/definitions\.json#\/definitions\/(.+)$/.exec(ref);
    if (common) {
      const d = this.def(COMMON_FILE, decodeURIComponent(common[1]));
      return d === undefined ? {} : { d };
    }
    return {}; // another provider's file: not followed
  }

  node(key, s, depth) {
    if (!s || typeof s !== 'object' || depth > 40) return {};
    if (s.$ref) return this.ref(key, s.$ref) ?? {};
    const parts = [];
    const alts = [...(s.oneOf ?? []), ...(s.anyOf ?? [])]
      .map((a) => (a && a.$ref ? this.ref(key, a.$ref) : this.node(key, a, depth + 1)))
      .filter((a) => a !== null);
    const own = this.own(key, s, depth);
    for (const a of s.allOf ?? []) parts.push(a && a.$ref ? this.ref(key, a.$ref) ?? {} : this.node(key, a, depth + 1));
    let out = own;
    for (const p of parts) out = merge(out, p, true);
    if (alts.length === 1) out = merge(out, alts[0], true);
    else if (alts.length > 1) {
      // Alternatives (a polymorphic body, or a value that is a string or an object):
      // take their union, requiring nothing any one of them requires.
      out = merge(out, alts.reduce((a, b) => union(a, b)), true);
    }
    return out;
  }

  own(key, s, depth) {
    const out = {};
    const t = Array.isArray(s.type) ? s.type[0] : s.type;
    const code = { string: 's', integer: 'i', number: 'n', boolean: 'b', object: 'o', array: 'a' }[t];
    if (code) out.t = code;
    if (Array.isArray(s.enum)) {
      const e = s.enum.filter((v) => typeof v === 'string');
      if (e.length && e.length === s.enum.length) out.e = e;
    }
    if (s.properties && typeof s.properties === 'object' && Object.keys(s.properties).length) {
      out.p = {};
      for (const [name, v] of Object.entries(s.properties)) out.p[name] = this.node(key, v, depth + 1);
      if (Array.isArray(s.required) && s.required.length) out.r = s.required.filter((r) => r in out.p);
      if (out.r && !out.r.length) delete out.r;
    }
    if (s.additionalProperties) {
      const m = s.additionalProperties === true ? {} : this.node(key, s.additionalProperties, depth + 1);
      if (out.p) out.o = 1;
      else if (Object.keys(m).length) out.m = m;
      else out.o = 1;
    } else if (!out.p && (out.t === 'o' || (!out.t && !s.items && !out.e))) {
      out.o = 1; // an object with nothing declared: anything goes
    }
    if (s.items) out.i = this.node(key, s.items, depth + 1);
    return pruneAny(out);
  }
}

/** An object node that checks nothing is `{}`. */
function pruneAny(n) {
  if (n.o && !n.p && !n.m && !n.e && !n.i) return n.t && n.t !== 'o' ? { t: n.t } : {};
  return n;
}

/** `a` and `b` both hold (allOf). */
function merge(a, b, keepRequired) {
  if (!Object.keys(a).length) return b;
  if (!Object.keys(b).length) return a;
  if (a.d !== undefined || b.d !== undefined) {
    // A reference and more: keep the reference, add the rest on top.
    if (a.d !== undefined && b.d !== undefined) return a.d === b.d ? a : { d: a.d, x: [b.d] };
    const [r, other] = a.d !== undefined ? [a, b] : [b, a];
    return { ...other, x: [...(other.x ?? []), r.d, ...(r.x ?? [])] };
  }
  const out = { ...a };
  if (b.t && !out.t) out.t = b.t;
  if (b.e) out.e = out.e ? out.e.filter((v) => b.e.includes(v)) : b.e;
  if (b.p) out.p = { ...(out.p ?? {}), ...b.p };
  if (keepRequired && b.r) out.r = [...new Set([...(out.r ?? []), ...b.r])];
  if (b.o) out.o = 1;
  if (b.m && !out.m) out.m = b.m;
  if (b.i && !out.i) out.i = b.i;
  if (b.x) out.x = [...(out.x ?? []), ...b.x];
  return out;
}

/** Either `a` or `b` (oneOf with several real alternatives). */
function union(a, b) {
  if (!Object.keys(a).length || !Object.keys(b).length) return {};
  if (a.d !== undefined && a.d === b.d && !a.x && !b.x) return a;
  const out = {};
  const refs = [a.d, ...(a.x ?? []), ...(a.u ?? []), b.d, ...(b.x ?? []), ...(b.u ?? [])].filter((d) => d !== undefined);
  if (refs.length) out.u = [...new Set(refs)]; // any-of references: their fields are all allowed, none required
  if (a.t === b.t && a.t) out.t = a.t;
  if (a.e && b.e) out.e = [...new Set([...a.e, ...b.e])];
  if (a.p || b.p) out.p = { ...(a.p ?? {}), ...(b.p ?? {}) };
  if (a.o || b.o) out.o = 1;
  if (a.i || b.i) out.i = a.i ?? b.i;
  if (a.m || b.m) out.m = a.m ?? b.m;
  if (!out.u && !out.p && !out.e && !out.i && !out.m) return out.t ? { t: out.t } : {};
  // A string-or-object value keeps the enum of the string form but must not
  // fail an object against it; mixing types is left unchecked.
  if ((a.e && !b.e) || (b.e && !a.e)) delete out.e;
  return out;
}

// ---------------------------------------------------------------- main ---

async function main() {
  console.log(`Listing ${REPO}@${BRANCH}${TOKEN ? ' (with GITHUB_TOKEN)' : ''}…`);
  const branch = await get(`https://api.github.com/repos/${REPO}/branches/${BRANCH}`).catch(() => undefined);
  const tree = await get(`https://api.github.com/repos/${REPO}/git/trees/${branch?.commit?.sha ?? BRANCH}?recursive=1`);
  if (tree.truncated) throw new Error('The git tree came back truncated; the index would be incomplete.');
  const commit = branch?.commit?.sha ?? tree.sha;
  const commitDate = branch?.commit?.commit?.committer?.date?.slice(0, 10);
  const raw = (path) => `https://raw.githubusercontent.com/${REPO}/${commit}/${path}`;
  const cacheDir = join(tmpdir(), 'atk-arm-schemas', commit.slice(0, 12));
  mkdirSync(cacheDir, { recursive: true });
  const fetchCached = async (path) => {
    const at = join(cacheDir, path.replace(/[\\/]/g, '__'));
    if (existsSync(at)) return JSON.parse(readFileSync(at, 'utf8'));
    const text = await get(raw(path), { json: false });
    writeFileSync(at, text);
    return JSON.parse(text);
  };

  // Every (apiVersion, file) the repository has.
  const files = new Map(); // file → Set(version)
  for (const { path, type } of tree.tree) {
    const m = type === 'blob' && /^schemas\/(\d{4}-\d{2}-\d{2}[^/]*)\/([^/]+)\.json$/.exec(path);
    if (!m) continue;
    if (!files.has(m[2])) files.set(m[2], new Set());
    files.get(m[2]).add(m[1]);
  }
  console.log(`  ${[...files.values()].reduce((n, s) => n + s.size, 0)} schema files, ${files.size} file names, commit ${commit.slice(0, 7)}`);

  // Which resource definitions each (version, file) holds, from the aggregate lists.
  console.log('Reading the aggregate resource lists…');
  const lists = ['schemas/common/autogeneratedResources.json', 'schemas/2018-05-01/subscriptionDeploymentTemplate.json', 'schemas/2019-08-01/managementGroupDeploymentTemplate.json', 'schemas/2019-08-01/tenantDeploymentTemplate.json'];
  const defs = new Map(); // "file|defName" → Set(version)
  for (const path of lists) {
    const text = JSON.stringify(await fetchCached(path));
    for (const m of text.matchAll(/schemas\/(\d{4}-\d{2}-\d{2}[^/]*)\/([^/"#]+)\.json#\/([A-Za-z_]*resourceDefinitions)\/([^"]+)"/g)) {
      const [, version, file, , name] = m;
      const key = `${file}|${name}`;
      if (!defs.has(key)) defs.set(key, new Set());
      defs.get(key).add(version);
    }
  }
  console.log(`  ${defs.size} resource definitions`);

  // The preferred version's file of each, plus each file name's newest stable
  // file (for extension resources the lists do not name).
  const want = new Set();
  for (const [key, versions] of defs) want.add(`${preferred(versions)}/${key.split('|')[0]}`);
  for (const [file, versions] of files) {
    if (/Deployment(Template|Parameters)|^deploymentTemplate$|^deploymentParameters$|^policyDefinition$|uiFormDefinition|CreateUIDefinition|\.Admin$/i.test(file)) continue;
    want.add(`${preferred(versions)}/${file}`);
  }
  const downloads = [...want].sort();
  console.log(`Downloading ${downloads.length} schema files…`);
  if (DRY) {
    for (const d of downloads) console.log(`  ${d}`);
    return;
  }
  const schemas = new Map();
  await pool(downloads, CONCURRENCY, async (key) => {
    try {
      schemas.set(key, await fetchCached(`schemas/${key}.json`));
    } catch (err) {
      console.warn(`  skipped ${key}: ${err.message}`);
    }
  });
  schemas.set(COMMON_FILE, await fetchCached('schemas/common/definitions.json'));

  // Type names: from the downloaded files' own definitions.
  const typeOfDef = new Map(); // "file|defName" → type
  const typeName = (body, name, file) => {
    const t = body?.properties?.type;
    const e = t?.enum?.[0] ?? (typeof t?.const === 'string' ? t.const : undefined);
    if (typeof e === 'string' && e.includes('/')) return e;
    const d = typeof body?.description === 'string' ? body.description.trim() : '';
    if (/^[A-Za-z0-9.]+\/[A-Za-z0-9/]+$/.test(d)) return d;
    void name;
    void file;
    return undefined;
  };
  const sections = (schema) => Object.keys(schema).filter((k) => /resourceDefinitions$/.test(k));
  // Types are case-insensitive, and the schemas spell some two ways
  // (microsoft.insights and Microsoft.Insights): one entry per type, under
  // the most usual spelling.
  const found = new Map(); // lower-cased type → { names: Map(spelling → count), versions:Set, best }
  const entryFor = (type) => {
    const key = type.toLowerCase();
    if (!found.has(key)) found.set(key, { names: new Map(), versions: new Set(), best: undefined });
    const entry = found.get(key);
    entry.names.set(type, (entry.names.get(type) ?? 0) + 1);
    return entry;
  };
  const nsOfFile = new Map();
  for (const [key, schema] of schemas) {
    if (key === COMMON_FILE) continue;
    const [version, file] = key.split('/');
    for (const section of sections(schema)) {
      for (const [name, body] of Object.entries(schema[section] ?? {})) {
        const type = typeName(body, name, file);
        if (!type) continue;
        typeOfDef.set(`${file}|${name}`, type);
        if (!nsOfFile.has(file)) nsOfFile.set(file, type.split('/')[0]);
        const entry = entryFor(type);
        entry.versions.add(version);
        if (!entry.best || better(version, entry.best.version)) entry.best = { version, file, def: name, section };
      }
    }
  }
  let derived = 0;
  for (const [key, versions] of defs) {
    const [file, name] = key.split('|');
    let type = typeOfDef.get(key);
    if (!type) {
      const ns = nsOfFile.get(file) ?? file.split('.').slice(0, 2).join('.');
      type = `${ns}/${name.replace(/_/g, '/')}`;
      derived += 1;
    }
    const entry = entryFor(type);
    for (const v of versions) entry.versions.add(v);
  }
  const spelling = (names) =>
    [...names].sort(([a, na], [b, nb]) => Number(/^[A-Z]/.test(b)) - Number(/^[A-Z]/.test(a)) || nb - na || (a < b ? -1 : 1))[0][0];
  // A namespace is spelt one way throughout, for the chunk files' sake.
  const nsSpelling = new Map();
  for (const entry of found.values()) {
    const ns = spelling(entry.names).split('/')[0];
    const k = ns.toLowerCase();
    if (!nsSpelling.has(k) || (/^[A-Z]/.test(ns) && !/^[A-Z]/.test(nsSpelling.get(k)))) nsSpelling.set(k, ns);
  }
  const types = new Map(); // type → { versions:Set, best:{version,file,def,section} }
  for (const entry of found.values()) {
    const [ns, ...rest] = spelling(entry.names).split('/');
    types.set([nsSpelling.get(ns.toLowerCase()), ...rest].join('/'), entry);
  }
  console.log(`  ${types.size} resource types (${derived} definition names not in a downloaded file, named from the definition)`);

  // Property schemas, a chunk per namespace.
  const byNs = new Map();
  for (const [type, entry] of types) {
    if (!entry.best) continue;
    const ns = type.split('/')[0];
    if (!byNs.has(ns)) byNs.set(ns, []);
    byNs.get(ns).push(type);
  }
  rmSync(DATA_OUT, { recursive: true, force: true });
  mkdirSync(DATA_OUT, { recursive: true });
  const chunkOf = new Map();
  let bytes = 0;
  let chunkCount = 0;
  let largest = ['', 0];
  const writeChunk = (id, typeList) => {
    const compactor = new Compactor(schemas);
    const out = { t: {}, d: compactor.defs };
    for (const type of typeList.sort()) {
      const { version, file, def, section } = types.get(type).best;
      const body = schemas.get(`${version}/${file}`)[section][def];
      const node = compactor.node(`${version}/${file}`, body, 0);
      // The template-level keys are the profile's business; keep the resource's own.
      if (node.p) for (const k of ['type', 'apiVersion', 'name', 'resources', 'dependsOn', 'comments', 'condition', 'copy', 'scope']) delete node.p[k];
      if (node.r) node.r = node.r.filter((r) => node.p && r in node.p);
      if (node.r && !node.r.length) delete node.r;
      out.t[type] = { v: version, s: node };
    }
    const text = JSON.stringify(out);
    return text;
  };
  for (const [ns, typeList] of [...byNs].sort()) {
    let groups = [typeList];
    let texts = [writeChunk(ns, typeList)];
    if (texts[0].length > CHUNK_LIMIT) {
      // Split by top-level type, packing groups up to the limit.
      const byTop = new Map();
      for (const t of typeList) {
        const top = t.split('/')[1];
        if (!byTop.has(top)) byTop.set(top, []);
        byTop.get(top).push(t);
      }
      groups = [];
      let cur = [];
      for (const [, ts] of [...byTop].sort()) {
        const trial = [...cur, ...ts];
        if (cur.length && writeChunk(ns, [...trial]).length > CHUNK_LIMIT) {
          groups.push(cur);
          cur = [...ts];
        } else cur = trial;
      }
      if (cur.length) groups.push(cur);
      texts = groups.map((g) => writeChunk(ns, [...g]));
    }
    groups.forEach((g, i) => {
      const id = groups.length === 1 ? ns : `${ns}.${i + 1}`;
      writeFileSync(join(DATA_OUT, `${id}.json`), texts[i]);
      bytes += texts[i].length;
      chunkCount += 1;
      if (texts[i].length > largest[1]) largest = [id, texts[i].length];
      for (const t of g) chunkOf.set(t, id);
    });
  }

  // The index: version lists are shared between types, and so are chunk names.
  const chunkNames = [...new Set(chunkOf.values())].sort();
  const listIds = new Map();
  const versionLists = [];
  const index = {};
  for (const [type, entry] of [...types].sort(([a], [b]) => (a.toLowerCase() < b.toLowerCase() ? -1 : 1))) {
    const vs = [...entry.versions].sort(compareVersions).join(',');
    if (!listIds.has(vs)) {
      listIds.set(vs, versionLists.length);
      versionLists.push(vs);
    }
    const [ns, ...rest] = type.split('/');
    index[ns] ??= {};
    const chunk = chunkOf.get(type);
    index[ns][rest.join('/')] = chunk === undefined ? [listIds.get(vs)] : [listIds.get(vs), chunkNames.indexOf(chunk)];
  }
  const data = {
    source: `https://github.com/${REPO}/tree/${commit}/schemas`,
    commit,
    commitDate,
    fetched: new Date().toISOString().slice(0, 10),
    chunks: chunkNames,
    versions: versionLists,
    types: index,
  };
  const indexText = `/**
 * Azure Resource Manager resource types and their apiVersions — GENERATED, do not edit by hand.
 *
 * Written by tools/fetch-editor-arm.mjs from Microsoft's published ARM schemas
 * (${data.source}). Refresh with: npm run editor:arm
 *
 * types: namespace → type (without the namespace) → [version list, chunk?].
 * versions: the version lists, comma-separated, newest first (a stable version
 * before the previews of the same date). chunks: the files under
 * web/data/editor/arm/ holding property schemas, read by ./arm-schema.ts.
 */

export interface ArmSchemaIndex {
  readonly source: string;
  readonly commit: string;
  readonly commitDate?: string;
  readonly fetched: string;
  readonly chunks: readonly string[];
  readonly versions: readonly string[];
  readonly types: Readonly<Record<string, Readonly<Record<string, readonly number[]>>>>;
}

export const ARM_SCHEMA_INDEX: ArmSchemaIndex = JSON.parse(${JSON.stringify(JSON.stringify(data))});
`;
  writeFileSync(INDEX_OUT, indexText);
  const withSchema = [...types.values()].filter((t) => t.best).length;
  console.log(`Wrote ${INDEX_OUT} (${(indexText.length / 1024).toFixed(0)} KB): ${types.size} types in ${Object.keys(index).length} namespaces, ${versionLists.length} distinct version lists`);
  console.log(`Wrote ${chunkCount} chunks to ${DATA_OUT}: ${(bytes / 1e6).toFixed(2)} MB, ${withSchema} types with a property schema; largest ${largest[0]} ${(largest[1] / 1024).toFixed(0)} KB`);
}

/** For choosing a type's property-schema version: any stable version beats a preview, then the newer. */
function better(a, b) {
  if (isStable(a) !== isStable(b)) return isStable(a);
  return compareVersions(a, b) < 0;
}

