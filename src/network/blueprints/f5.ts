/** AS3 wraps everything in a declaration with a tenant and an application. */
interface As3Options {
  readonly tenant: string;
  readonly application: string;
  readonly label: string;
  readonly body: Record<string, unknown>;
}

function declaration({ tenant, application, label, body }: As3Options): Record<string, unknown> {
  return {
    $schema: 'https://raw.githubusercontent.com/F5Networks/f5-appsvcs-extension/main/schema/latest/as3-schema.json',
    class: 'AS3',
    action: 'deploy',
    persist: true,
    declaration: {
      class: 'ADC',
      schemaVersion: '3.45.0',
      id: `archtoolkit-${application.toLowerCase()}`,
      label,
      remark: 'Generated by ArchToolKit — review before deploying.',
      [tenant]: {
        class: 'Tenant',
        [application]: {
          class: 'Application',
          template: 'generic',
          ...body,
        },
      },
    },
  };
}

const json = (value: unknown): string[] => JSON.stringify(value, null, 2).split('\n');

/** Members typed as "10.20.30.11:443, 10.20.30.12:443". */
function members(value: string, defaultPort: number): { servers: string[]; port: number } {
  const parts = listOf(value);
  let port = defaultPort;
  const servers: string[] = [];
  for (const part of parts) {
    const [address, typed] = part.split(':');
    if (address) servers.push(address);
    if (typed && Number.isFinite(Number(typed))) port = Number(typed);
  }
  return { servers, port };
}

