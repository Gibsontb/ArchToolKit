/**
 * F5 BIG-IP, as AS3 declarations.
 *
 * A BIG-IP can be configured three ways: tmsh by hand, iControl REST object by
 * object, or a declaration that says what the application should look like and
 * lets the device work out the difference. The declaration is the one worth
 * generating: it is idempotent, it is reviewable as a whole, and it is the same
 * artefact whether it is posted by hand, by Ansible, or by a pipeline.
 *
 * So these blueprints emit AS3 JSON rather than tmsh, and the Data Editor
 * already carries the AS3 schema — a declaration generated here can be opened
 * there and checked against it.
 *
 * Certificates and keys are never written into a declaration here. Where TLS is
 * wanted, the declaration references a certificate that already exists on the
 * device, and says so.
 */

