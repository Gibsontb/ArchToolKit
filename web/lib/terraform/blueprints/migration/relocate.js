function googleGcve()            {
  return {
    id: 'google_mig_gcve',
    label: 'Google Cloud VMware Engine (relocate)',
    group: MIGRATION_GROUP,
    description: 'A VMware Engine network, a private cloud for the VMs that move unchanged with HCX, and the peering that joins it to the landing zone\'s VPC.',
    inputs: [
      ...commonInputs({ label: 'Node type', options: ['standard-72', 've1-standard-72', 've2-standard-128'], default: 'standard-72' }, '10.200.0.0/22', 'The management range (a /22 or larger); it must not overlap anything.'),
      LANDING_ZONE_SOURCE,
    ],
    emits: ['google_vmwareengine_network', 'google_vmwareengine_private_cloud', 'google_vmwareengine_network_peering'],
    build: (values                 ) => {
      const findings            = [];
      const lz = lzRef(values);
      const cidr = valueOf(values, 'management_cidr', '10.200.0.0/22');
      const net = rname(valueOf(values, 'network', 'prod'));
      if (familyOf(cidr) !== 4 || Number(cidr.split('/')[1]) > 22) findings.push(error('tf.mig.gcve-cidr', `"${cidr}" is not an IPv4 /22 or larger.`, { path: 'management_cidr' }));
      if (findings.length > 0) return failed('google_mig_gcve', findings);
      const blocks             = [
        terraformBlock(['google']),
        ...consumerPreamble('google', values),
        res('google_vmwareengine_network', 'relocate', { name: x(`"\${${lz}.prefix}-vmware"`), location: 'global', type: 'STANDARD', description: 'VMware Engine network for relocated VMs' }),
        res('google_vmwareengine_private_cloud', 'relocate', {
          name: x(`"\${${lz}.prefix}-gcve"`),
          location: x(`element(${lz}.zones, 0)`),
          description: 'Private cloud for the VMs HCX relocates',
        }, [
          blk('network_config', { management_cidr: cidr, vmware_engine_network: x('google_vmwareengine_network.relocate.id') }),
          blk('management_cluster', { cluster_id: x(`"\${${lz}.prefix}-mgmt"`) }, [blk('node_type_configs', { node_type_id: valueOf(values, 'sku_name', 'standard-72'), node_count: numberOf(values, 'node_count', 3) })]),
        ]),
        res('google_vmwareengine_network_peering', 'relocate', {
          name: x(`"\${${lz}.prefix}-vmware-${net}"`),
          vmware_engine_network: x('google_vmwareengine_network.relocate.id'),
          peer_network: x(`${lz}.network_ids[${q(net)}]`),
          peer_network_type: 'STANDARD',
          export_custom_routes: true,
          import_custom_routes: true,
        }),
        output('private_cloud_id', 'google_vmwareengine_private_cloud.relocate.id'),
        output('hcx', 'google_vmwareengine_private_cloud.relocate.hcx'),
      ];
      return { files: { 'main.tf': mainTf(blocks, 'Google Cloud VMware Engine for the relocated VMs') }, findings };
    },
  };
}

