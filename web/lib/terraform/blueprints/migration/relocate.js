/**
 * Relocate: the VMware service on each cloud that HCX moves VMs into unchanged.
 *
 *   azure_mig_avs    Azure VMware Solution private cloud, and an ExpressRoute
 *                    authorisation to connect it to the hub
 *   google_mig_gcve  Google Cloud VMware Engine network, private cloud and the
 *                    peering to the landing zone's VPC
 *   oci_mig_ocvs     Oracle Cloud VMware Solution SDDC, with the VLANs and
 *                    provisioning subnet it needs in the landing zone's VCN
 *
 * AWS has none: Amazon EVS has no resource in the aws provider this kit is
 * pinned to (6.66), so the AWS relocate path is a runbook, not Terraform.
 *
 * The node count comes from the plan's estimate; the real sizing is the VCF
 * Sizing page's. Each reads the landing zone as every other migration
 * blueprint does.
 */

import { error, info,              } from '../../../core/findings.js';
import { familyOf } from '../../../core/ip.js';
                                                                                            
import { num as numberOf, str as valueOf } from '../../../kit/blueprint.js';
                                             
import {
  LANDING_ZONE_SOURCE,
  MIGRATION_GROUP,
  blk,
  carve,
  consumerPreamble,
  e,
  hcl,
  ident,
  lzRef,
  mainTf,
  opts,
  output,
  q,
  res,
  rname,
  sshKeyVariable,
  terraformBlock,
  x,
} from './common.js';

const failed = (id        , findings                    ) => ({
  files: { 'main.tf': `# ${id}: nothing was generated; see the findings.\n` },
  findings,
});

function commonInputs(sku                                                                , cidr        , cidrHint        )                   {
  return [
    { id: 'sku_name', label: sku.label, control: 'select', default: sku.default, options: opts(sku.options) },
    { id: 'node_count', label: 'Hosts', control: 'number', default: 3, min: 3, max: 16, hint: 'From the plan\'s estimate; size it properly on the VCF Sizing page.' },
    { id: 'management_cidr', label: 'Management range', control: 'text', default: cidr, hint: cidrHint },
    { id: 'network', label: 'Network', control: 'text', default: 'prod', hint: 'The landing-zone network it connects to.' },
  ];
}

// ---------------------------------------------------------------------------
// Azure VMware Solution
// ---------------------------------------------------------------------------

function azureAvs()            {
  return {
    id: 'azure_mig_avs',
    label: 'Azure VMware Solution (relocate)',
    group: MIGRATION_GROUP,
    description: 'An Azure VMware Solution private cloud for the VMs that move unchanged with HCX, and an ExpressRoute authorisation key to connect it to the hub\'s ExpressRoute gateway (Global Reach to on-premises is configured on the circuit).',
    inputs: [
      ...commonInputs({ label: 'Host SKU', options: ['av36p', 'av52', 'av64', 'av36', 'av48'], default: 'av36p' }, '10.200.0.0/22', 'A /22 for vCenter, NSX Manager, HCX and the hosts; it must not overlap anything.'),
      LANDING_ZONE_SOURCE,
    ],
    emits: ['azurerm_vmware_private_cloud', 'azurerm_vmware_express_route_authorization'],
    build: (values                 ) => {
      const findings            = [];
      const lz = lzRef(values);
      const cidr = valueOf(values, 'management_cidr', '10.200.0.0/22');
      if (familyOf(cidr) !== 4 || !cidr.endsWith('/22')) findings.push(error('tf.mig.avs-cidr', `"${cidr}" is not an IPv4 /22, which is what Azure VMware Solution takes.`, { path: 'management_cidr' }));
      if (findings.length > 0) return failed('azure_mig_avs', findings);
      const blocks             = [
        terraformBlock(['azure']),
        ...consumerPreamble('azure', values),
        res('azurerm_vmware_private_cloud', 'relocate', {
          name: x(`"\${${lz}.prefix}-avs"`),
          resource_group_name: x(`${lz}.resource_group["shared"]`),
          location: x(`${lz}.location`),
          sku_name: valueOf(values, 'sku_name', 'av36p'),
          network_subnet_cidr: cidr,
          internet_connection_enabled: false,
        }, [blk('management_cluster', { size: numberOf(values, 'node_count', 3) })], 'The vCenter and NSX Manager passwords are generated by Azure and read from the portal or the API; none is written here.'),
        res('azurerm_vmware_express_route_authorization', 'hub', { name: x(`"\${${lz}.prefix}-hub"`), private_cloud_id: x('azurerm_vmware_private_cloud.relocate.id') }),
        output('private_cloud_id', 'azurerm_vmware_private_cloud.relocate.id'),
        output('express_route_circuit_id', 'azurerm_vmware_private_cloud.relocate.circuit[0].express_route_id', 'Connect it to the hub ExpressRoute gateway with the authorisation key.'),
        output('express_route_authorization_key', 'azurerm_vmware_express_route_authorization.hub.express_route_authorization_key', undefined, true),
        output('hcx_cloud_manager', 'azurerm_vmware_private_cloud.relocate.hcx_cloud_manager_endpoint'),
      ];
      findings.push(info('tf.mig.avs-connect', 'Connect the private cloud\'s ExpressRoute to the hub ExpressRoute gateway (a gateway connection with the authorisation key), and enable Global Reach to the on-premises circuit for HCX.', { path: 'network' }));
      return { files: { 'main.tf': mainTf(blocks, 'Azure VMware Solution for the relocated VMs') }, findings };
    },
  };
}

