/** The VLANs an OCVS SDDC needs, each with its own /25 of the SDDC range. */
const OCVS_VLANS = [
  ['nsx_edge_uplink1', 'NSX Edge uplink 1'],
  ['nsx_edge_uplink2', 'NSX Edge uplink 2'],
  ['nsx_edge_vtep', 'NSX Edge VTEP'],
  ['nsx_vtep', 'NSX VTEP'],
  ['vmotion', 'vMotion'],
  ['vsan', 'vSAN'],
  ['vsphere', 'vSphere'],
  ['hcx', 'HCX'],
  ['replication', 'Replication'],
  ['provisioning', 'Provisioning'],
]         ;

function ociOcvs()            {
  return {
    id: 'oci_mig_ocvs',
    label: 'Oracle Cloud VMware Solution (relocate)',
    group: MIGRATION_GROUP,
    description: 'An Oracle Cloud VMware Solution SDDC for the VMs that move unchanged with HCX, with its VLANs and provisioning subnet carved in the landing zone\'s VCN, and a workload cluster when asked.',
    inputs: [
      ...commonInputs({ label: 'Host shape', options: ['BM.DenseIO.E5.128', 'BM.DenseIO.E4.128', 'BM.DenseIO2.52'], default: 'BM.DenseIO.E5.128' }, '10.200.0.0/21', 'A /21: ten VLANs and the provisioning subnet each take a /25 of it.'),
      { id: 'vmware_software_version', label: 'VMware software version', control: 'text', default: '8.0 update 3', hint: 'As OCVS lists it for the region (oci ocvs supported-vmware-software-version-summary list).' },
      { id: 'workload_hosts', label: 'Workload cluster hosts', control: 'number', default: 0, min: 0, max: 64, hint: '0: management cluster only.' },
      { id: 'vcf_byol_allocation_id', label: 'VCF BYOL allocation', control: 'text', default: '', hint: 'The OCID of a portable VCF subscription allocation, when the licence is brought.' },
      { id: 'ssh_public_key_var', label: 'SSH key variable', control: 'text', default: 'ssh_public_key' },
      LANDING_ZONE_SOURCE,
    ],
    emits: ['oci_core_vlan', 'oci_core_subnet', 'oci_ocvp_sddc', 'oci_ocvp_cluster'],
    build: (values                 ) => {
      const findings            = [];
      const lz = lzRef(values);
      const cidr = valueOf(values, 'management_cidr', '10.200.0.0/21');
      const net = rname(valueOf(values, 'network', 'prod'));
      const prefix = Number(cidr.split('/')[1]);
      const pieces = familyOf(cidr) === 4 && prefix <= 21 ? carve(cidr, [...OCVS_VLANS.map(() => 25), 25]) : null;
      if (!pieces) findings.push(error('tf.mig.ocvs-cidr', `"${cidr}" is not an IPv4 /21 or larger, which the SDDC's VLANs and subnet need.`, { path: 'management_cidr' }));
      if (!pieces) return failed('oci_mig_ocvs', findings);
      const ssh = ident(valueOf(values, 'ssh_public_key_var', 'ssh_public_key'));
      const byol = valueOf(values, 'vcf_byol_allocation_id');
      const workload = numberOf(values, 'workload_hosts', 0);
      const ad = `element(${lz}.zones, 0)`;
      const vcn = `${lz}.network_ids[${q(net)}]`;
      const blocks             = [terraformBlock(['oci']), ...consumerPreamble('oci', values), sshKeyVariable(ssh)];
      OCVS_VLANS.forEach(([id, label], i) => {
        blocks.push(
          res('oci_core_vlan', `ocvs_${id}`, {
            compartment_id: x(`${lz}.compartment_id`),
            vcn_id: x(vcn),
            availability_domain: x(ad),
            cidr_block: pieces[i]          ,
            vlan_tag: 100 + i,
            display_name: x(`"\${${lz}.prefix}-ocvs-${id.replace(/_/g, '-')}"`),
            nsg_ids: x(`[${lz}.security_group_ids[${q(`${net}/mgmt`)}]]`),
          }, [], `${label}.`),
        );
      });
      blocks.push(
        res('oci_core_subnet', 'ocvs_provisioning', {
          compartment_id: x(`${lz}.compartment_id`),
          vcn_id: x(vcn),
          cidr_block: pieces[OCVS_VLANS.length]          ,
          display_name: x(`"\${${lz}.prefix}-ocvs-provisioning"`),
          prohibit_public_ip_on_vnic: true,
        }),
      );
      const vlan = (id        ) => x(`oci_core_vlan.ocvs_${id}.id`);
      const networkConfig = blk('network_configuration', {
        provisioning_subnet_id: x('oci_core_subnet.ocvs_provisioning.id'),
        nsx_edge_uplink1vlan_id: vlan('nsx_edge_uplink1'),
        nsx_edge_uplink2vlan_id: vlan('nsx_edge_uplink2'),
        nsx_edge_vtep_vlan_id: vlan('nsx_edge_vtep'),
        nsx_vtep_vlan_id: vlan('nsx_vtep'),
        vmotion_vlan_id: vlan('vmotion'),
        vsan_vlan_id: vlan('vsan'),
        vsphere_vlan_id: vlan('vsphere'),
        hcx_vlan_id: vlan('hcx'),
        replication_vlan_id: vlan('replication'),
        provisioning_vlan_id: vlan('provisioning'),
      });
      blocks.push(
        res('oci_ocvp_sddc', 'relocate', {
          compartment_id: x(`${lz}.compartment_id`),
          display_name: x(`"\${${lz}.prefix}-ocvs"`),
          vmware_software_version: valueOf(values, 'vmware_software_version', '8.0 update 3'),
          ssh_authorized_keys: x(`var.${ssh}`),
          hcx_action: 'UPGRADE',
        }, [
          blk('initial_configuration', {}, [
            blk('initial_cluster_configurations', {
              compute_availability_domain: x(ad),
              esxi_hosts_count: numberOf(values, 'node_count', 3),
              vsphere_type: 'MANAGEMENT',
              initial_host_shape_name: valueOf(values, 'sku_name', 'BM.DenseIO.E5.128'),
              initial_vcf_byol_allocation_id: byol || undefined,
              display_name: 'management',
              instance_display_name_prefix: 'esx',
            }, [networkConfig]),
          ]),
        ], 'HCX Enterprise (hcx_action UPGRADE) for bulk and vMotion migration.'),
      );
      if (workload > 0) {
        blocks.push(
          res('oci_ocvp_cluster', 'workload', {
            sddc_id: x('oci_ocvp_sddc.relocate.id'),
            compute_availability_domain: x(ad),
            esxi_hosts_count: workload,
            initial_host_shape_name: valueOf(values, 'sku_name', 'BM.DenseIO.E5.128'),
            display_name: 'workload',
            initial_vcf_byol_allocation_id: byol || undefined,
          }, [networkConfig]),
        );
      }
      blocks.push(output('sddc_id', 'oci_ocvp_sddc.relocate.id'), output('vlans', hcl(Object.fromEntries(OCVS_VLANS.map(([id]) => [id, e(`oci_core_vlan.ocvs_${id}.cidr_block`)])), 1)));
      findings.push(info('tf.mig.ocvs-version', 'The VMware software versions OCVS offers change by region; check the version before applying.', { path: 'vmware_software_version' }));
      return { files: { 'main.tf': mainTf(blocks, 'Oracle Cloud VMware Solution for the relocated VMs') }, findings };
    },
  };
}

